export function normalizeBookTitle(value = '') {
  return String(value)
    .normalize('NFKC')
    .replace(/\s+/g, ' ')
    .trim()
    .toLocaleLowerCase('ko');
}

const VERIFIED_TITLE_KEYS = new Set(MILLIE_VERIFIED_TITLES.map(normalizeBookTitle));

export function isVerifiedMillieTitle(title = '') {
  const key = normalizeBookTitle(title);
  return Boolean(key) && VERIFIED_TITLE_KEYS.has(key);
}

export function applyVerifiedMillieStatus(book = {}) {
  const current = book.millieStatus || 'unchecked';
  if (current !== 'unchecked') return current;
  return isVerifiedMillieTitle(book.title) ? 'full' : current;
}
